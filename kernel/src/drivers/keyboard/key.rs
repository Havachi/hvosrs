#[repr(u8)]
pub enum KeyCode {
	Escape,
	F1,
	F2,
	F3,
	F4,
	F5,
	F6,
	F7,
	F8,
	F9,
	F10,
	F11,
	F12,
	PrintScreen,
	SysRq,
	ScrollLock,
	PauseBreak,
	///Symbol key on the left of `Key1`
	Oem8,

	Key1,
	Key2,
	Key3,
	Key4,
	Key5,
	Key6,
	Key7,
	Key8,
	Key9,
	Key0,
	OemMinus,
	OemEqual,
	Backspace,
	Insert,
	Home,
	PageUp,
	NumpadLock,
	NumpadDivide,
	NumpadMultiply,
	NumpadSubstract,
	Tab,
	Q,W,E,R,T,Y,U,I,O,P,
	///Left-Square-Bracket Key
	Oem4,
	///Right-Square-Bracket Key
	Oem6,
	///Backslash Key
	Oem5,
	///Hash/Tilde
	Oem7,
	Delete,
	End,
	PageDown,
	Numpad7,
	Numpad8,
	Numpad9,
	NumpadAdd,
	CapsLock,
	A,S,D,F,G,H,J,K,L,
	///Semicolon / Colon key
	Oem1,
	///Single-Quote/At Key
	Oem3,
	Return,
	Numpad4,
	Numpad5,
	Numpad6,
	LShift,
	Z,X,C,V,B,N,M,
	//US ANSI ',<' key
	OemComma,
	//US ANSI '.>' key
	OemPeriod,
	///US ANSI '/?' Key
	Oem2,

	RShift,
	ArrowUp,
	Numpad1,
	Numpad2,
	Numpad3,
	NumpadEnter,
	LControl,
	///The right-hand start key AKA Windows Key
	LStart,
	LAlt,
	Spacebar,
	///The 'Apps' key (aka 'Menu' or 'Right-Click')
	Apps,
	RControl,
	ArrowLeft,
	ArrowDown,
	ArrowRight,
	Numpad0,
	NumpadPeriod,
	Unknown,
}


pub fn map_scancode(code: u8) -> Option<KeyCode> {
	match code {
		0x00 => None,
		0x01 => Some(KeyCode::Escape),
		0x02 => Some(KeyCode::Key1),
		0x03 => Some(KeyCode::Key2),
		0x04 => Some(KeyCode::Key3),
		0x05 => Some(KeyCode::Key4),
		0x06 => Some(KeyCode::Key5),
		0x07 => Some(KeyCode::Key6),
		0x08 => Some(KeyCode::Key7),
		0x09 => Some(KeyCode::Key8),
		0x0A => Some(KeyCode::Key9),
		0x0B => Some(KeyCode::Key0),
		0x0C => Some(KeyCode::OemMinus),
		0x0D => Some(KeyCode::OemEqual),
		0x0E => Some(KeyCode::Backspace),
		0x0F => Some(KeyCode::Tab),

		0x10 => Some(KeyCode::Q),
		0x11 => Some(KeyCode::W),
		0x12 => Some(KeyCode::E),
		0x13 => Some(KeyCode::R),
		0x14 => Some(KeyCode::T),
		0x15 => Some(KeyCode::Y),
		0x16 => Some(KeyCode::U),
		0x17 => Some(KeyCode::I),
		0x18 => Some(KeyCode::O),
		0x19 => Some(KeyCode::P),
		0x1A => Some(KeyCode::Oem4),
		0x1B => Some(KeyCode::Oem6),
		0x1C => Some(KeyCode::Return),
		0x1D => Some(KeyCode::LControl),
		0x1E => Some(KeyCode::A),
		0x1F => Some(KeyCode::S),

		0x20 => Some(KeyCode::D),
		0x21 => Some(KeyCode::F),
		0x22 => Some(KeyCode::G),
		0x23 => Some(KeyCode::H),
		0x24 => Some(KeyCode::J),
		0x25 => Some(KeyCode::K),
		0x26 => Some(KeyCode::L),
		0x27 => Some(KeyCode::Oem1),
		0x28 => Some(KeyCode::Oem3),
		0x29 => Some(KeyCode::Oem8),
		0x2A => Some(KeyCode::LShift),
		0x2B => Some(KeyCode::Oem7),
		0x2C => Some(KeyCode::Z),
		0x2D => Some(KeyCode::X),
		0x2E => Some(KeyCode::C),
		0x2F => Some(KeyCode::V),

		0x30 => Some(KeyCode::B),
		0x31 => Some(KeyCode::N),
		0x32 => Some(KeyCode::M),
		0x33 => Some(KeyCode::OemComma),
		0x34 => Some(KeyCode::OemPeriod),
		0x35 => Some(KeyCode::Oem2),
		0x36 => Some(KeyCode::RShift),
		0x37 => Some(KeyCode::NumpadMultiply),
		0x38 => Some(KeyCode::LAlt),
		0x39 => Some(KeyCode::Spacebar),
		0x3A => Some(KeyCode::CapsLock),
		0x3B => Some(KeyCode::F1),
		0x3C => Some(KeyCode::F2),
		0x3D => Some(KeyCode::F3),
		0x3E => Some(KeyCode::F4),
		0x3F => Some(KeyCode::F5),

		0x40 => Some(KeyCode::F6),
		0x41 => Some(KeyCode::F7),
		0x42 => Some(KeyCode::F8),
		0x43 => Some(KeyCode::F9),
		0x44 => Some(KeyCode::F10),
		0x45 => Some(KeyCode::NumpadLock),
		0x46 => Some(KeyCode::ScrollLock),
		0x47 => Some(KeyCode::Numpad7),
		0x48 => Some(KeyCode::Numpad8),
		0x49 => Some(KeyCode::Numpad9),
		0x4A => Some(KeyCode::NumpadSubstract),
		0x4B => Some(KeyCode::Numpad4),
		0x4C => Some(KeyCode::Numpad5),
		0x4D => Some(KeyCode::Numpad6),
		0x4E => Some(KeyCode::NumpadAdd),
		0x4F => Some(KeyCode::Numpad1),
	
		0x50 => Some(KeyCode::Numpad2),
		0x51 => Some(KeyCode::Numpad3),
		0x52 => Some(KeyCode::Numpad0),
		0x53 => Some(KeyCode::NumpadPeriod),
		0x54 => Some(KeyCode::SysRq),
		//0x55 unused
		0x56 => Some(KeyCode::Oem5),
		0x57 => Some(KeyCode::F11),
		0x58 => Some(KeyCode::F12),
		_ => None
	}
}